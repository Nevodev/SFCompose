from pathlib import Path
import gzip
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "app/src/main/assets/symbols"
CATALOG = ROOT / "shrink-prototype/catalog/src/main"
RAW = CATALOG / "res/raw"
INDEX = json.loads((ASSETS / "index.json").read_text(encoding="utf-8"))
SYMBOLS = [
    ("Wifi", "wifi", False, None, ("Small", "Medium", "Large")),
    ("PersonFill", "person.fill", True, ("Regular", "Semibold", "Bold"), ("Small", "Medium", "Large")),
    ("ZeroCircle", "0.circle", False, ("Regular", "Bold"), ("Small", "Medium")),
    ("ZeroCircleAr", "0.circle.ar", False, ("Regular", "Bold"), ("Small", "Medium")),
]
def main():
    RAW.mkdir(parents=True, exist_ok=True)
    resources = ET.Element("resources")
    entries = []
    kotlin = [
        "package com.nevoit.shrinkprototype.catalog",
        "",
        "// Generated by shrink-prototype/generate_combinations.py.",
        "object SymbolCombinations {",
    ]
    previous_manifest = ROOT / "shrink-prototype/combinations.json"
    previous = json.loads(previous_manifest.read_text(encoding="utf-8")) if previous_manifest.exists() else []
    for prefix, name, filled, allowed_weights, allowed_scales in SYMBOLS:
        with gzip.open(ASSETS / f"{name}.json.sfgz", "rt", encoding="utf-8") as stream:
            source = json.load(stream)
        closure = f"closure_{prefix.lower()}"
        closure_payload = {"kind": "symbol-metadata", "name": name, "layerTree": source["layerTree"]}
        (RAW / f"{closure}.sfgz").write_bytes(gzip.compress(json.dumps(closure_payload, ensure_ascii=False,
            separators=(",", ":")).encode("utf-8"), mtime=0))
        for weight, position in INDEX["weights"].items():
            if allowed_weights is not None and weight not in allowed_weights:
                continue
            for scale in allowed_scales:
                selected = [master for master in source["scales"][scale.lower()]["masters"]
                            if master["weight"] == position]
                if len(selected) != 1:
                    raise ValueError(f"Missing or ambiguous master {name}/{weight}/{scale}")
                resource = f"combo_{prefix.lower()}_{weight.lower()}_{scale.lower()}"
                payload = {
                    "name": name,
                    "weight": weight,
                    "scale": scale,
                    "filled": filled,
                    "upm": source["upm"],
                    "capHeight": source["capHeight"],
                    "master": selected[0],
                }
                output = RAW / f"{resource}.sfgz"
                output.write_bytes(gzip.compress(json.dumps(payload, ensure_ascii=False,
                    separators=(",", ":")).encode("utf-8"), mtime=0))
                array = ET.SubElement(resources, "integer-array", name=resource)
                ET.SubElement(array, "item").text = f"@raw/{resource}"
                ET.SubElement(array, "item").text = f"@raw/{closure}"
                accessor = f"{prefix}{weight}{scale}"
                kotlin.append(f'    val {accessor} get() = SymbolRef("{name}", R.array.{resource}, "{weight}", "{scale}", {str(filled).lower()})')
                entries.append({"accessor": accessor, "resource": resource, "name": name,
                                "weight": weight, "scale": scale, "filled": filled, "closure": closure})
    kotlin.extend(["", "    val Wifi get() = WifiRegularSmall", "}"])
    wifi_entries = [entry for entry in entries if entry["name"] == "wifi"]
    if len(wifi_entries) != 27:
        raise ValueError("Full wifi fixture must contain 27 combinations")
    full_array = ET.SubElement(resources, "integer-array", name="full_wifi")
    for entry in wifi_entries:
        ET.SubElement(full_array, "item").text = f'@raw/{entry["resource"]}'
    ET.SubElement(full_array, "item").text = "@raw/closure_wifi"
    regular_array = ET.SubElement(resources, "integer-array", name="family_wifi_regular")
    for entry in wifi_entries:
        if entry["weight"] == "Regular":
            ET.SubElement(regular_array, "item").text = f'@raw/{entry["resource"]}'
    ET.SubElement(regular_array, "item").text = "@raw/closure_wifi"
    (CATALOG / "java/com/nevoit/shrinkprototype/catalog/SymbolCombinations.kt").write_text(
        "\n".join(kotlin) + "\n", encoding="utf-8")
    ET.indent(resources, space="    ")
    ET.ElementTree(resources).write(CATALOG / "res/values/combinations.xml", encoding="utf-8", xml_declaration=True)
    (ROOT / "shrink-prototype/combinations.json").write_text(
        json.dumps(entries, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    active = {entry["resource"] for entry in entries}
    for entry in previous:
        if entry["resource"] not in active:
            (RAW / f'{entry["resource"]}.sfgz').unlink(missing_ok=True)
    print(f"Generated {len(entries)} combinations and their resource references")


if __name__ == "__main__":
    main()
